    private BotaniaAspects() {
    }

    private static void add(String item, Object... aspects) {
        ITEMS.put(item, aspects);
    }

    private static void floating(String flower) {
        Object[] base = ITEMS.get(flower);
        if (base == null) {
            return;
        }
        Object[] pairs = new Object[base.length + 4];
        System.arraycopy(base, 0, pairs, 0, base.length);
        pairs[base.length] = "volatus";
        pairs[base.length + 1] = 3;
        pairs[base.length + 2] = "vacuos";
        pairs[base.length + 3] = 1;
        ITEMS.put("floating_" + flower, pairs);
    }

    private static void colors(String suffix, Object... aspects) {
        for (String color : COLORS) {
            add(color + "_" + suffix, aspects);
        }
    }

    public static Iterable<String> items() {
        return ITEMS.keySet();
    }

    public static void addTo(JsonObject values) {
        for (Map.Entry<String, Object[]> entry : ITEMS.entrySet()) {
            Object[] pairs = entry.getValue().clone();
            for (int i = 0; i < pairs.length; i += 2) {
                pairs[i] = ASPECT + pairs[i];
            }
            JsonObject json = new JsonObject();
            json.add("neoforge:conditions", conditions());
            json.add("value", ContentJson.aspects(pairs));
            values.add(BotaniaIntegration.MOD_ID + ":" + entry.getKey(), json);
        }
    }

    private static JsonArray conditions() {
        return BotaniaJson.conditions(BotaniaIntegration.ASPECTS);
    }
